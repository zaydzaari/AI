// Self-hosts the lab's Google Fonts (replacing faces Impeccable flags as overused).
//   node scripts/lab-fonts.mjs
// Writes public/lab-fonts/<concept>/fonts/*.woff2 and components/designs/<concept>/fonts.generated.css.
import fs from "node:fs";
import path from "node:path";
import { fontFaces } from "../awwwards-20-collection/_build/fonts.mjs";

const ROOT = path.resolve(path.dirname(new URL(import.meta.url).pathname), "..");
const PLAN = {
  d01: [{ family: "Newsreader", axes: "ital,opsz,wght@0,6..72,400..600;1,6..72,400..500" }],
  d06: [{ family: "Albert Sans", axes: "wght@400;500;600;700" }],
  d09: [{ family: "Public Sans", axes: "wght@400..700" }],
  d12: [{ family: "Literata", axes: "ital,opsz,wght@0,7..72,300..600;1,7..72,300..500" }],
};
for (const [id, specs] of Object.entries(PLAN)) {
  const dir = path.join(ROOT, "public", "lab-fonts", id);
  fs.rmSync(dir, { recursive: true, force: true });
  const { css, files } = fontFaces(dir, specs, `/lab-fonts/${id}/fonts/`);
  fs.writeFileSync(path.join(ROOT, "components", "designs", id, "fonts.generated.css"), `/* Generated by scripts/lab-fonts.mjs — do not edit. */\n${css}`);
  console.log(`${id}: ${files.length} font file(s)`);
}

// Tweaks font library: the collection's faces, copied into public/tweak-fonts so the lab's
// Tweaks panel can offer the same menu.
const COLL = path.join(ROOT, "awwwards-20-collection");
const gallery = fs.readFileSync(path.join(COLL, "index.html"), "utf8");
const lib = JSON.parse(gallery.match(/window\.AE_FONTS = (\[.*?\]);/)[1]);
const out = path.join(ROOT, "public", "tweak-fonts");
fs.rmSync(out, { recursive: true, force: true });
fs.mkdirSync(out, { recursive: true });
const list = lib.map((f) => {
  const name = path.basename(f.url);
  fs.copyFileSync(path.join(COLL, f.url), path.join(out, name));
  return { name: f.name, style: f.style, url: `/tweak-fonts/${name}` };
});
fs.writeFileSync(path.join(ROOT, "lib", "tweak-fonts.generated.json"), JSON.stringify(list, null, 2) + "\n");
console.log(`tweak-fonts: ${list.length} faces`);
